#!/usr/bin/env python3
"""Prepare the logo images shown as holograms next to Education / Experience entries (writes logos.js).

Put a crop of each logo (on its normal white background) in tools/logos/NAME.png, then:
    python3 tools/make-logos.py

For each logo: the white page background is removed (flood-filled from the edges, so
white parts *inside* a logo survive), colours are adapted for a dark site, the result is
squared up, and stored as a small transparent PNG. The page projects them as holograms.

Colour modes (per logo, see MODES):
  keep    leave colours as they are (logo has its own light/dark parts)
  light   dark ink becomes light (black text -> white, navy -> light blue)
  invert  flip the lightness of greys (a pale tile becomes a dark tile, dark text white)
  tile    like keep, but black is lifted to dark grey so a black square logo shows as a tile
"""
import base64, colorsys, io, json, os
from collections import deque
from PIL import Image, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
MODES = {"uva": "tile", "vossius": "keep", "vu": "light", "zonnegilde": "light",
         "tudelft": "light", "loyens": "light", "ebrain": "invert"}
SIZE = 200

def background_mask(im, tol=34):
    w, h = im.size
    px = im.load()
    bg = [[False] * w for _ in range(h)]
    near_white = lambda c: (255 - c[0]) + (255 - c[1]) + (255 - c[2]) < tol * 3
    q = deque((x, y) for x in range(w) for y in (0, h - 1)) + deque((x, y) for y in range(h) for x in (0, w - 1))
    while q:
        x, y = q.popleft()
        if not (0 <= x < w and 0 <= y < h) or bg[y][x] or not near_white(px[x, y]): continue
        bg[y][x] = True
        q.extend(((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)))
    return bg

def adapt(rgb, mode):
    r, g, b = (c / 255 for c in rgb)
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    if mode == "light" and (l < 0.42 or (s < 0.25 and l < 0.55)):
        l = 0.93 - l * 0.55 if s < 0.25 else 1 - l
    elif mode == "invert" and s < 0.35:
        l = 1 - l
    elif mode == "tile" and l < 0.2:
        l = 0.2                     # keep a black square visible as a dark tile
    return tuple(int(c * 255) for c in colorsys.hls_to_rgb(h, l, s))

out = {}
for fn in sorted(os.listdir(os.path.join(HERE, "logos"))):
    if not fn.endswith(".png") or fn.startswith("."): continue
    name = fn[:-4]
    mode = MODES.get(name, "light")
    im = Image.open(os.path.join(HERE, "logos", fn)).convert("RGB")
    bg = background_mask(im)
    w, h = im.size
    src = im.load()
    rgba = Image.new("RGBA", (w, h))
    dst = rgba.load()
    for y in range(h):
        for x in range(w):
            if bg[y][x]: dst[x, y] = (0, 0, 0, 0)
            else: dst[x, y] = adapt(src[x, y], mode) + (255,)
    a = rgba.split()[3].filter(ImageFilter.GaussianBlur(0.6))     # soften the cut edge
    rgba.putalpha(a)
    bbox = rgba.getbbox() or (0, 0, w, h)
    rgba = rgba.crop(bbox)
    side = int(max(rgba.size) * 1.12)
    sq = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    sq.paste(rgba, ((side - rgba.width) // 2, (side - rgba.height) // 2), rgba)
    sq = sq.resize((SIZE, SIZE), Image.LANCZOS)
    flat = Image.new("RGB", (SIZE, SIZE), (0, 0, 0))     # preview on black
    flat.paste(sq, (0, 0), sq)
    buf = io.BytesIO()
    sq.save(buf, "PNG", optimize=True)                    # page uses the transparent version
    out[name] = "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()
    os.makedirs(os.path.join(HERE, "logos", "preview"), exist_ok=True)
    flat.save(os.path.join(HERE, "logos", "preview", f"{name}.png"))
    print(f"{name:12s} {mode:7s} -> {len(buf.getvalue()) // 1024 + 1} KB")

with open(os.path.join(HERE, "..", "logos.js"), "w") as f:
    f.write("/* generated by tools/make-logos.py */\nwindow.LOGOS = {\n")
    for k, v in out.items(): f.write(f"  {json.dumps(k)}: '{v}',\n")
    f.write("};\n")
print("wrote logos.js")
